/* V4 visual layer only: canvas network, subtle 3D tilt and staggered reveals. Content data above remains unchanged. */
document.addEventListener("DOMContentLoaded", () => {
  const prefersReduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  const addNetworkCanvas = () => {
    if (prefersReduced || document.getElementById("matrixCanvas")) return;
    const canvas = document.createElement("canvas");
    canvas.id = "matrixCanvas";
    canvas.setAttribute("aria-hidden", "true");
    document.body.prepend(canvas);
    const ctx = canvas.getContext("2d");
    let width = 0;
    let height = 0;
    let nodes = [];
    const pointer = { x: -9999, y: -9999 };

    const resize = () => {
      width = canvas.width = Math.floor(window.innerWidth * window.devicePixelRatio);
      height = canvas.height = Math.floor(window.innerHeight * window.devicePixelRatio);
      canvas.style.width = `${window.innerWidth}px`;
      canvas.style.height = `${window.innerHeight}px`;
      const count = Math.min(82, Math.max(34, Math.floor(window.innerWidth / 19)));
      nodes = Array.from({ length: count }, () => ({
        x: Math.random() * width,
        y: Math.random() * height,
        vx: (Math.random() - .5) * .26 * window.devicePixelRatio,
        vy: (Math.random() - .5) * .26 * window.devicePixelRatio,
        r: (Math.random() * 1.6 + .8) * window.devicePixelRatio
      }));
    };

    const draw = () => {
      ctx.clearRect(0, 0, width, height);
      const maxDist = 145 * window.devicePixelRatio;
      const px = pointer.x * window.devicePixelRatio;
      const py = pointer.y * window.devicePixelRatio;
      for (const node of nodes) {
        node.x += node.vx;
        node.y += node.vy;
        if (node.x < 0 || node.x > width) node.vx *= -1;
        if (node.y < 0 || node.y > height) node.vy *= -1;
      }
      for (let i = 0; i < nodes.length; i++) {
        const a = nodes[i];
        for (let j = i + 1; j < nodes.length; j++) {
          const b = nodes[j];
          const dx = a.x - b.x;
          const dy = a.y - b.y;
          const d = Math.hypot(dx, dy);
          if (d < maxDist) {
            const alpha = (1 - d / maxDist) * .22;
            ctx.strokeStyle = `rgba(102,232,255,${alpha})`;
            ctx.lineWidth = .7 * window.devicePixelRatio;
            ctx.beginPath();
            ctx.moveTo(a.x, a.y);
            ctx.lineTo(b.x, b.y);
            ctx.stroke();
          }
        }
        const pd = Math.hypot(a.x - px, a.y - py);
        if (pd < 190 * window.devicePixelRatio) {
          ctx.strokeStyle = `rgba(181,108,255,${(1 - pd / (190 * window.devicePixelRatio)) * .24})`;
          ctx.lineWidth = .8 * window.devicePixelRatio;
          ctx.beginPath();
          ctx.moveTo(a.x, a.y);
          ctx.lineTo(px, py);
          ctx.stroke();
        }
        ctx.fillStyle = "rgba(170,244,255,.78)";
        ctx.beginPath();
        ctx.arc(a.x, a.y, a.r, 0, Math.PI * 2);
        ctx.fill();
      }
      requestAnimationFrame(draw);
    };

    window.addEventListener("resize", resize, { passive: true });
    window.addEventListener("pointermove", event => { pointer.x = event.clientX; pointer.y = event.clientY; }, { passive: true });
    resize();
    draw();
  };

  const addTilt = () => {
    if (prefersReduced) return;
    document.addEventListener("pointermove", event => {
      const card = event.target.closest?.(".project-card, .profile-card, .contact-card, .edu-card");
      if (!card) return;
      const rect = card.getBoundingClientRect();
      const x = (event.clientX - rect.left) / rect.width - .5;
      const y = (event.clientY - rect.top) / rect.height - .5;
      const amount = card.classList.contains("profile-card") ? 6 : 3.2;
      card.style.transform = `perspective(900px) rotateX(${(-y * amount).toFixed(2)}deg) rotateY(${(x * amount).toFixed(2)}deg) translateY(-5px)`;
    }, { passive: true });
    document.addEventListener("pointerout", event => {
      const card = event.target.closest?.(".project-card, .profile-card, .contact-card, .edu-card");
      if (card) card.style.transform = "";
    }, { passive: true });
  };

  const addStagger = () => {
    const setDelay = selector => document.querySelectorAll(selector).forEach((el, i) => {
      el.style.transitionDelay = `${Math.min(i * 45, 360)}ms`;
    });
    setDelay(".experience-card");
    setDelay(".project-card");
    setDelay(".skill-card");
    setDelay(".edu-card");
    setDelay(".cert-card");
    setDelay(".contact-card");
  };

  setTimeout(() => {
    addNetworkCanvas();
    addTilt();
    addStagger();
  }, 80);
});
